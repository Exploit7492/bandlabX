"""Generate one evidence test file per new resource for the Phase 3.1 leaves.

Each generated test calls the resource method and asserts the URL that reaches `fetch`, which is
the same evidence pattern used by the hand-written songs/revisions tests. The rows come from
`api.md`; required parameter fields come from the `*Params` interfaces in `src/resources/**`, so a
method that needs `userId` in its body gets a real value instead of an empty object.

Usage: python3 scripts/research/gen-31-tests.py
"""
import io
import os
import sys
import re

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

SECTIONS = [
    # (title, test directory, client accessor, source file, method filter or None)
    ('Albums', 'albums', 'albums', 'src/resources/albums.ts', None),
    ('Effects', 'effects', 'effects', 'src/resources/effects.ts', None),
    ('Sounds', 'sounds', 'sounds', 'src/resources/sounds/sounds.ts', None),
    ('Uploads', 'uploads', 'uploads', 'src/resources/uploads.ts', None),
    ('Soundbanks', 'soundbanks', 'soundbanks', 'src/resources/soundbanks.ts', None),
    ('AI', 'ai', 'ai', 'src/resources/ai/ai.ts', None),
    ('AI Videos', 'ai-videos', 'aiVideos', 'src/resources/ai-videos.ts', None),
    ('Synced Lyrics', 'synced-lyrics', 'syncedLyrics', 'src/resources/synced-lyrics.ts', None),
    ('Misc', 'misc', 'misc', 'src/resources/misc.ts', None),
    ('Tracks', 'tracks', 'tracks', 'src/resources/tracks.ts', None),
    # Bands already has hand-written tests; only the Phase 3.1 additions are generated here.
    ('Bands', 'bands', 'bands', 'src/resources/bands/bands.ts', {
        'listSuggested', 'listFollowers', 'addFollower',
        'listMemberFollowInvitees', 'pinPost', 'listVideoPosts',
    }),
]

ROW = re.compile(
    r'^- <code title="([a-z]+) ([^"]+)">client\.(\S+?)\.<a href="\./([^"]+)">(\w+)</a>'
    r'(?:\((.*?)\))? -> (.+?)</code>$'
)

PLACEHOLDER = '182bd5e5-6e1a-4fe4-a799-aa6d9a6ab26e'

HEADER = """// Evidence-backed request-path tests for the {title} leaf (Phase 3.1).
//
// Generated by scripts/research/gen-31-tests.py from the rows in api.md, which in turn come from
// docs/research/apk-endpoints.md. Each test calls the method and inspects the URL that actually
// reaches `fetch`, so a rename or a route regression fails here rather than in production.

import BandlabSDK from 'bandlab-sdk';

function makeClient(): BandlabSDK {{
  return new BandlabSDK({{ bearerToken: 'My Bearer Token', baseURL: 'http://127.0.0.1:4010' }});
}}

/** Run `fn`, capture the URL of the first request, and answer it with a stub response. */
async function captureURL(fn: (c: BandlabSDK) => Promise<unknown>): Promise<string> {{
  const calls: string[] = [];
  const realFetch = globalThis.fetch;
  globalThis.fetch = (async (input: any) => {{
    calls.push(typeof input === 'string' ? input : input?.url ?? String(input));
    return new Response('{{}}', {{ status: 200, headers: {{ 'content-type': 'application/json' }} }});
  }}) as typeof fetch;
  try {{
    await fn(makeClient()).catch(() => undefined);
  }} finally {{
    globalThis.fetch = realFetch;
  }}
  if (!calls.length) throw new Error('no request was issued');
  return calls[0]!;
}}

describe('{title} paths match the APK evidence', () => {{
"""


def api_rows():
    api = io.open(os.path.join(REPO, 'api.md'), encoding='utf-8').read()
    for line in api.split('\n'):
        m = ROW.match(line.strip())
        if m:
            verb, path, accessor, source, method, args, _ret = m.groups()
            yield verb, path, accessor, source, method, args or ''


def required_fields(source, iface):
    """Return the required property names of `export interface <iface>`."""
    if not iface:
        return []
    src = io.open(os.path.join(REPO, source), encoding='utf-8').read()
    m = re.search(r'^export interface %s \{\n(.*?)^\}' % re.escape(iface), src, re.M | re.S)
    if not m:
        return []
    fields = []
    for prop in re.finditer(r'^  (\w+)(\??): (.*?);$', m.group(1), re.M):
        if not prop.group(2):  # no `?` means the field is required
            fields.append(prop.group(1))
    return fields


def params_interface(source, method):
    """The `*Params` interface used by `method`, if any."""
    src = io.open(os.path.join(REPO, source), encoding='utf-8').read()
    m = re.search(r'^  %s\((.*?)\): APIPromise' % re.escape(method), src, re.M | re.S)
    if not m:
        return None
    found = re.findall(r'(\w+Params)\b', m.group(1))
    return found[-1] if found else None


def value_for(field):
    return '{}' if field == 'body' else "'%s'" % PLACEHOLDER


def build_params_object(source, method, args):
    """Replace the trailing `{ ...params }` with an object literal of required fields."""
    if '{ ...params }' not in args:
        return args
    fields = required_fields(source, params_interface(source, method))
    literal = '{ %s }' % ', '.join('%s: %s' % (f, value_for(f)) for f in fields) if fields else '{}'
    return args.replace('{ ...params }', literal)


def split_top_level(raw):
    """Split an argument list on commas that are not inside brackets."""
    parts, depth, cur = [], 0, ''
    for ch in raw:
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def build_call(accessor, method, args):
    """Turn an api.md signature into a callable expression with placeholder arguments."""
    parts = []
    for arg in split_top_level(args):
        if arg.startswith('{'):
            parts.append(arg)
        else:
            parts.append("'%s'" % PLACEHOLDER)
    return 'c.%s.%s(%s)' % (accessor, method, ', '.join(parts))


def literal_path(path):
    return re.sub(r'\{[^}]+\}', PLACEHOLDER, path)


def main():
    force = '--force' in sys.argv
    rows = list(api_rows())
    for title, directory, accessor, source, method_filter in SECTIONS:
        mine = [r for r in rows if r[2] == accessor]
        if method_filter is not None:
            mine = [r for r in mine if r[4] in method_filter]
        if not mine:
            continue
        target = os.path.join(REPO, 'tests', 'api-resources', directory, 'evidence.test.ts')
        # Scaffolding only: never clobber a file a session has hand-edited. Pass --force to rewrite.
        if os.path.exists(target) and not force:
            print('skipped %s (exists; use --force to rewrite)' % target)
            continue
        out = [HEADER.format(title=title)]
        for verb, path, _acc, row_source, method, args in mine:
            args = build_params_object(row_source, method, args)
            call = build_call(accessor, method, args)
            out.append("  test('%s %s hits %s', async () => {" % (verb.upper(), path, path))
            out.append('    const url = await captureURL((c) => %s);' % call)
            out.append("    expect(url).toContain('%s');" % literal_path(path))
            out.append('  });')
            out.append('')
        out.append('});')
        os.makedirs(os.path.dirname(target), exist_ok=True)
        io.open(target, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
        print('wrote %s (%d tests)' % (target, len(mine)))


if __name__ == '__main__':
    main()
