"""Generate one evidence test file per new resource for the Phase 3.1 leaves.

Each generated test calls the resource method and asserts the URL that reaches `fetch`, which is
the same evidence pattern used by the hand-written songs/revisions tests. The rows come from
`api.md`; required parameter fields come from the `*Params` interfaces in `src/resources/**`, so a
method that needs `userId` in its body gets a real value instead of an empty object.

Usage: python3 scripts/research/gen-31-tests.py
"""
